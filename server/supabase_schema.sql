-- ========================================================
-- Supabase SQL Schema for White Matrix AI Chatbot & Leads
-- Run this in your Supabase SQL Editor (SQL Editor -> New Query)
-- ========================================================

-- 1. Chat Messages Table (stores conversation history)
CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('user', 'model', 'assistant', 'system')),
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Index for fast session retrieval
CREATE INDEX IF NOT EXISTS idx_chat_messages_session ON chat_messages(session_id);

-- 2. Leads Table (stores captured visitor contacts and inquiries)
CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT,
    name TEXT,
    email TEXT,
    phone TEXT,
    service TEXT,
    message TEXT,
    source TEXT DEFAULT 'chatbot',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Index for leads
CREATE INDEX IF NOT EXISTS idx_leads_created_at ON leads(created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE chat_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE leads ENABLE ROW LEVEL SECURITY;

-- The server writes with the anon key. Chat and lead records are private and
-- should not be readable through public policies.
DROP POLICY IF EXISTS "Allow public read on chat_messages" ON chat_messages;
DROP POLICY IF EXISTS "Allow public read on leads" ON leads;
DROP POLICY IF EXISTS "Allow public insert on chat_messages" ON chat_messages;
DROP POLICY IF EXISTS "Allow public insert on leads" ON leads;

CREATE POLICY "Allow public insert on chat_messages"
    ON chat_messages FOR INSERT TO anon
    WITH CHECK (true);

CREATE POLICY "Allow public insert on leads"
    ON leads FOR INSERT TO anon
    WITH CHECK (true);

